CREATE TABLE almacen (
                         id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         nombre       VARCHAR(100) NOT NULL UNIQUE,
                         descripcion  VARCHAR(255),
                         codigo_qr    VARCHAR(100) UNIQUE
);
--6 almacenes + 6 de pedi

CREATE TABLE ubicacion (
                           id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           almacen_id   BIGINT NOT NULL REFERENCES almacen(id),
                           nombre       VARCHAR(100) NOT NULL,
                           descripcion  VARCHAR(255),
                           UNIQUE (almacen_id, nombre)
); -- dentro del almacen

CREATE TABLE categoria (
                           id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           nombre  VARCHAR(100) NOT NULL UNIQUE
); -- tipo de cada material

CREATE TABLE producto (
                          id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          categoria_id   BIGINT REFERENCES categoria(id),
                          nombre         VARCHAR(150) NOT NULL,
                          unidad_medida  VARCHAR(30) NOT NULL DEFAULT 'unidad',
                          activo         BOOLEAN NOT NULL DEFAULT TRUE
);

-- Cuántas unidades hay de cada producto en cada almacén
CREATE TABLE existencia (
                            id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            almacen_id      BIGINT NOT NULL REFERENCES almacen(id),
                            producto_id     BIGINT NOT NULL REFERENCES producto(id),
                            ubicacion_id    BIGINT REFERENCES ubicacion(id),
                            cantidad        INTEGER NOT NULL DEFAULT 0 CHECK (cantidad >= 0),
                            stock_minimo    INTEGER NOT NULL DEFAULT 0 CHECK (stock_minimo >= 0),
                            actualizado_en  TIMESTAMP NOT NULL DEFAULT NOW(),
                            UNIQUE NULLS NOT DISTINCT (almacen_id, producto_id, ubicacion_id)
);

-- Personas que usan la app (sin roles ni contraseña)
CREATE TABLE usuario (
                         id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         nombre  VARCHAR(100) NOT NULL UNIQUE,
                         activo  BOOLEAN NOT NULL DEFAULT TRUE
);

-- Historial: cada entrada, salida, ajuste o traslado
CREATE TABLE movimiento (
                            id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            tipo                VARCHAR(20) NOT NULL
                                CHECK (tipo IN ('ENTRADA', 'SALIDA', 'AJUSTE', 'TRASLADO')),
                            almacen_id          BIGINT NOT NULL REFERENCES almacen(id),
                            almacen_destino_id  BIGINT REFERENCES almacen(id),
                            producto_id         BIGINT NOT NULL REFERENCES producto(id),
                            usuario_id          BIGINT NOT NULL REFERENCES usuario(id),
                            cantidad            INTEGER NOT NULL CHECK (cantidad >= 0),
                            fecha               TIMESTAMP NOT NULL DEFAULT NOW()
);

-- Equipos de electromedicina, uno por fila
CREATE TABLE equipo_electromedicina (
                                        id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                        producto_id      BIGINT NOT NULL REFERENCES producto(id),
                                        almacen_id       BIGINT NOT NULL REFERENCES almacen(id),
                                        numero_serie     VARCHAR(100) NOT NULL UNIQUE,
                                        estado           VARCHAR(20) NOT NULL DEFAULT 'OPERATIVO'
                                            CHECK (estado IN ('OPERATIVO', 'AVERIADO', 'NECESITA_REVISION')),
                                        ultima_revision  DATE
);

-- Índices para que las consultas frecuentes sean rápidas

--Indice 1. la accion mas frecuente de la app--> alguien escanea el QR y se le tendra que mostrar lo que hay en ese almacen
--Sin indice habria que recorrer el inventario de todos los almacenes
CREATE INDEX idx_existencia_almacen ON existencia (almacen_id);

-- Indice 2. Ultimos movimientos del almacen en el que se encuentra( del mas reciente al mas antiguo), cada vez que se pulsa + o -, se añade una fila
--Primero agrupa por almacen y dentro del almacen por fecha
CREATE INDEX idx_movimiento_almacen_fecha ON movimiento (almacen_id, fecha DESC);

--Indice 3. Busqueda de productos por nombre
CREATE INDEX idx_producto_nombre ON producto (LOWER(nombre));


